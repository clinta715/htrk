        v.widgets.noninteractive.bg_fill = self.status_bg;
        v.widgets.noninteractive.fg_stroke.color = self.fg_text;
        v.widgets.inactive.bg_fill = self.transport_bg;
        v.widgets.inactive.fg_stroke.color = self.transport_fg;
